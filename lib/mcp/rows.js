/**
 * Single source of truth for the three Aura MCP loader rows.
 *
 * Everything the MCP wiring needs is rendered from here:
 *   - `renderBundlePatch()`  -> this package's own `cordis.patch.yml`. This is the SHIPPED
 *                               shape: the bundle layer, installed by `plugin_manager`.
 *   - `renderManagedBlockBody()` -> the `# >>> aura-mcp managed >>>` block for the patch-layer
 *                               shape, which lives in `~/.dsh/profiles/web/cordis.patch.yml`
 *                               and hot-reloads. It is the ALTERNATIVE shape, not the default.
 *   - `renderHeadlessOverlay()` -> a standalone `- insert:` overlay for
 *                               `dsh --profile headless --patch <file>`.
 *
 * The two shapes must never both provide the same row id: the loader's
 * duplicate check (`cordis-plugin-loader/lib/index.js` -> `TypeError: duplicate loader
 * entry id`) makes the whole profile fail to boot. `lib/mcp/channels.js` is the guard.
 *
 * ZERO imports on purpose: this module is consumed by the package CLI and by tests, and
 * it must never drag in a dependency that the profile's module fallback may not have.
 *
 * The `!!js` expression shape is byte-for-byte the one that has been running in
 * `profiles/web/cordis.patch.yml` since the Aura wiring was first generated; two real
 * bugs are pinned by tests and must not come back:
 *   1. `pathIsLiteral` — the candidate paths are single-quoted JS strings containing
 *      `\\` escapes. Emitting them with a single backslash turns `\next` into a newline
 *      and silently destroys the first candidate path.
 *   2. `bomTolerated` — a Notepad-saved JSON file starts with U+FEFF; `JSON.parse`
 *      throws on it and the row silently degrades to the fallback literal, so the BOM
 *      is stripped before parsing.
 *
 * @module dsh-aura/lib/mcp/rows
 */

